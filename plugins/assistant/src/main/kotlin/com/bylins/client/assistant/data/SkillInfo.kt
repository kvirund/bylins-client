    /**
     * Конвертировать словесное описание в примерный процент.
     */
    fun levelDescToPercent(desc: String): Int {
        val key = desc.lowercase().trim()
        val range = skillLevelDescriptions.entries.find {
            it.key.equals(key, ignoreCase = true)
        }?.value
        return range?.let { (it.first + it.last) / 2 } ?: 0
    }

